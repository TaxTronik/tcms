export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  className = 'tx-icon',
  title,
}: {
  name: IconName | string;
  className?: string;
  title?: string;
}) {
  const C = (ICONS as Record<string, LucideIcon>)[name] ?? Circle;
  return title ? (
    <C className={className} aria-label={title} role="img" />
  ) : (
    <C className={className} aria-hidden="true" />
  );
}
